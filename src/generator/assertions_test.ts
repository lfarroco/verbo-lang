Deno.test("generateAssertions output type-checks against its generated types", async () => {
  // Integration: write types.verbo.ts + .verbo/validate.ts to a temp project and
  // run `deno check` on the assertions module. Needs the `run` test permission
  // (provided by `./dev test`, which passes `-P`).
  const dir = Deno.makeTempDirSync({ prefix: "verbo-assertions-test-" });
  try {
    Deno.writeTextFileSync(
      `${dir}/types.verbo.ts`,
      [
        "export type Student = { name: string; email: string; gradeLevel: number; enrollmentDate: Date; classes: Class[] };",
        "export type Teacher = { name: string; email: string; department: string; hireDate: Date; classes: Class[] };",
        "export type Class = { name: string; subject: string; room: string; maxStudents: number; teacher: Teacher; students: Student[] };",
      ].join("\n"),
    );
    Deno.mkdirSync(`${dir}/.verbo`, { recursive: true });
    Deno.writeTextFileSync(
      `${dir}/.verbo/validate.ts`,
      generateAssertions(classroom),
    );

    const cmd = new Deno.Command("deno", {
      args: ["check", `${dir}/.verbo/validate.ts`],
      stdout: "piped",
      stderr: "piped",
    });
    const result = await cmd.output();
    const stderr = new TextDecoder().decode(result.stderr);
    assertEquals(result.success, true, stderr);
  } finally {
    Deno.removeSync(dir, { recursive: true });
  }
});
